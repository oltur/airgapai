#!/usr/bin/env python3
"""Regenerates docs/hours.md from Claude Code session timestamps and git commit times.

Does nothing when no session logs exist, as on a clean clone or in CI.
To start a phase, set its start time in PHASES.
"""
import json
import re
import subprocess
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path

IDLE_GAP = timedelta(minutes=15)
PHASES = [  # name, budget in hours, start
    ("0: repo basics", 5, "2026-10-31T09:13:00+01:00"),
    ("1: the air gap", 60, "2026-10-31T09:41:27+01:00"),
    ("2: light retrieval", 30, "2026-11-01T13:20:00+01:00"),
    ("3: agent gateway", 55, None),
    ("4: evals and write-up", 30, None),
]

ROOT = Path(__file__).resolve().parent.parent
HEADER = f"""# Hours

Generated by `scripts/hours.py`; do not edit. Active time is measured from Claude Code session
activity and git commits. A gap over {IDLE_GAP.seconds // 60} minutes ends a block, and a block
counts from its first event to its last. This is an approximation: it misses work done away from
those tools, and it counts time when Claude was working unattended.
"""


def parse(stamp):
    return datetime.fromisoformat(stamp.replace("Z", "+00:00")).astimezone()


def session_events():
    logs = Path.home() / ".claude/projects" / re.sub(r"[^A-Za-z0-9]", "-", str(ROOT))
    for log in logs.rglob("*.jsonl") if logs.is_dir() else ():
        with log.open(errors="replace") as lines:
            for line in lines:
                try:
                    stamp = json.loads(line).get("timestamp")
                    if stamp:
                        yield parse(stamp)
                except (ValueError, AttributeError):
                    continue


def commit_events():
    out = subprocess.run(
        ["git", "log", "--all", "--format=%aI"], cwd=ROOT, capture_output=True, text=True
    )
    return [parse(line) for line in out.stdout.split()]


def blocks(events):
    """Returns (start, end) pairs of continuous activity."""
    result = []
    for event in sorted(events):
        if result and event - result[-1][1] <= IDLE_GAP:
            result[-1][1] = event
        else:
            result.append([event, event])
    return result


def main():
    sessions = list(session_events())
    if not sessions:
        return
    starts = [parse(start) for _, _, start in PHASES if start]
    events = sessions + commit_events()

    by_phase = defaultdict(timedelta)
    by_day = defaultdict(timedelta)
    # Blocks are built per phase, so one spanning a phase start is split at that point.
    for phase, phase_start in enumerate(starts):
        phase_end = starts[phase + 1] if phase + 1 < len(starts) else None
        in_phase = (e for e in events if e >= phase_start and (phase_end is None or e < phase_end))
        for start, end in blocks(in_phase):
            by_phase[phase] += end - start
            by_day[start.date(), phase] += end - start

    def hours(delta):
        return f"{delta.total_seconds() / 3600:.1f}"

    rows = [HEADER, "| Phase | Budget (h) | Active (h) |", "|---|---|---|"]
    for index, (name, budget, start) in enumerate(PHASES):
        actual = hours(by_phase[index]) if start else ""
        over = " **budget reached: stop and choose**" if by_phase[index] >= timedelta(hours=budget) else ""
        rows.append(f"| {name} | {budget} | {actual}{over} |")
    rows += ["", "## By day", "", "| Date | Phase | Active (h) |", "|---|---|---|"]
    for (day, phase), delta in sorted(by_day.items()):
        rows.append(f"| {day} | {phase} | {hours(delta)} |")
    (ROOT / "docs/hours.md").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
